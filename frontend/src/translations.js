export function getSavedLanguage() {
  if (typeof window === "undefined") return "zh";
  return window.localStorage.getItem("touhou-project-language") === "en" ? "en" : "zh";
}

export function translateMessage(text, language = getSavedLanguage(), values = {}) {
  const template = language === "en" ? text : (traditionalChinese[text] || text);
  return template.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? `{${key}}`));
}

export function translateApiError(text, language = getSavedLanguage()) {
  return language === "en" ? (apiErrorMessages[text] || text) : text;
}
